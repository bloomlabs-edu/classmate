/**
 * models/Lesson.js
 *
 * The scheduled teaching entity — one occurrence of teaching one piece
 * of curriculum content, assigned to one Teaching Slot (see
 * models/TeachingSlot.js). References curriculum content by id only,
 * never copies it: `curriculumUnitId` and `conceptIds` are resolved
 * live against the Curriculum domain at display time, the same
 * reference-not-copy principle already established for
 * AssessmentSubject.subjectId and Learning Management's Subject ->
 * Curriculum Index link. Curriculum stays the single source of truth;
 * a unit renamed or a concept reworded later needs no Lesson
 * migration.
 *
 * `conceptIds` is an array, not a single `conceptId` — this is a
 * deliberate difference from the earlier draft of this model. Two
 * reasons: it gives the "Concept Builder isn't built yet" fallback
 * (see services/plannerStrategies/balancedStrategy.js) a natural
 * empty-array representation (`conceptIds: []` for a whole-unit
 * placeholder lesson) rather than a special-cased null, and it leaves
 * room for a future strategy to schedule more than one concept per
 * lesson without another model change.
 *
 * `teachingSlotId` references models/TeachingSlot.js's own generated
 * id — not the slot's date/period directly, so a Lesson's origin slot
 * stays traceable even if slot data is later regenerated or replaced
 * by a different source (manual entry today, a real Timetable
 * eventually).
 *
 * `estimatedMinutes` is populated from the originating Teaching Slot's
 * own `duration` at generation time — what the lesson was scheduled
 * to take. `actualMinutes` stays null until a teacher records it after
 * the fact; nothing in this milestone sets it.
 *
 * `status` — 'planned' | 'taught' | 'skipped' | 'rescheduled'. Nothing
 * in this milestone changes it after creation (no calendar UI, no
 * teacher-facing status controls yet) — see
 * services/plannerService.js's recordLessonStatusChange() for the one
 * piece of status-transition logic this milestone does include, ready
 * for a future UI to call.
 *
 * `planningCycleId` — nullable. A Lesson generated by the Planner
 * engine's balanced strategy always has one; a Lesson created directly
 * by attaching a lesson plan to a Timetable period (see
 * services/timetableLessonService.js) does not belong to any
 * PlanningCycle at all, and null is the correct, real value for it —
 * never a fabricated placeholder id.
 *
 * `objectives`/`bigQuestion` — the WEEKLY PLAN's own lightweight
 * content (see docs/CLASSMATE_WEEKLY_PLAN_AND_LESSON_PLAN_ARCHITECTURE.md):
 * "why are students learning this" reduced to what a routine,
 * non-observed period actually needs — a concept, at least one real
 * objective, and a Big Question. Same shape as
 * models/LessonPlan.js's own `objectives[]`/`bigQuestion` (reuses
 * `createLessonPlanObjective()` directly — one shared shape, not a
 * parallel one) but this is NOT a live reference to any LessonPlan;
 * it's this Lesson's own copy, editable independently, entered directly
 * on the Timetable's Period Detail panel. Most periods stop here —
 * see services/weeklyPlanValidationService.js's own getWeeklyPlanReadiness().
 *
 * `planSummary`/`assessmentNote` — the two remaining fields the Weekly
 * Plan review grid needs (Unit/Topic/Big Question/Objective/Plan/
 * Assessment) that this model didn't already have. Free text, nullable,
 * deliberately named to avoid colliding with models/LessonPlan.js's own
 * vocabulary (`activities[]`, `assessments[]`) — these are the Weekly
 * Plan's own concise "what will happen" / "how will you check
 * understanding" notes, never a copy of a LessonPlan's detailed
 * content, and never required for a LessonPlan to exist. Edited
 * alongside Objectives/Big Question on the same Timetable Period Detail
 * "Plan" tab; read live by services/weeklyPlanSubmissionService.js's
 * review grid, never snapshotted anywhere.
 *
 * `lessonPlanId` — nullable. Set exactly once, the moment a teacher
 * chooses "Build Detailed Lesson Plan" for this period (see
 * services/timetableLessonService.js's own buildDetailedLessonPlanFromLesson()) —
 * that action creates a real models/LessonPlan.js document, SEEDED from
 * this Lesson's own conceptIds/curriculumUnitId/objectives/bigQuestion,
 * and records its id here so the Period Detail panel can tell "no
 * detailed plan yet" from "one already exists" with a single field
 * check, never a live query. `null` is the default, expected state for
 * most periods — a Lesson is never required to grow a LessonPlan just
 * because it exists.
 *
 * `executedConceptIds` — subset of `conceptIds`: which of the PLANNED
 * concepts were actually taught in this specific occurrence (see
 * services/timetableLessonService.js's markConceptsExecuted(), which
 * is the only place this is ever set, and enforces the subset
 * invariant). Deliberately separate from the classroom-level
 * `LearningConcept.status` ('taught'/'not_taught') — that flag is
 * shared across the whole syllabus tree and flips once, the first time
 * a concept is genuinely executed anywhere; `executedConceptIds` is
 * this one Lesson's own record of what happened in this one occurrence,
 * which is what "only executed concepts are eligible for student
 * feedback" (per this occurrence) actually needs. A planned concept
 * NOT in `executedConceptIds` was either not yet taught, or — see
 * `carriedForwardConceptIds` below — moved to a different occurrence
 * instead.
 */

import { generateId } from '../utils/idGenerator.js';
import { createLessonPlanObjective } from './LessonPlan.js';

export function createLesson({
  id,
  planningCycleId = null,
  classroomId,
  date,
  teachingSlotId,
  curriculumUnitId,
  conceptIds = [],
  executedConceptIds = [],
  carriedForwardConceptIds = [],
  conceptProvenance = {},
  objectives = [],
  bigQuestion = '',
  planSummary = null,
  assessmentNote = null,
  lessonPlanId = null,
  // Pre-existing latent bug, fixed here: with no default, this stayed
  // `undefined` for any Lesson created outside services/plannerStrategies/
  // balancedStrategy.js (the only caller that ever explicitly supplies
  // it) — and Firestore's setDoc() rejects any field whose value is
  // `undefined` outright. Every other genuinely-optional field on this
  // model already defaults to `null` for exactly this reason
  // (planningCycleId, estimatedMinutes, actualMinutes below); this one
  // was simply missed until services/timetableLessonService.js's
  // attachLessonPlan() became the first caller that doesn't supply it.
  sequenceIndex = null,
  estimatedMinutes = null,
  actualMinutes = null,
  status = 'planned',
  teacherReflection = null,
  feedbackSharedAt = null,
  // Holiday rescheduling milestone — append-only audit trail of every
  // concept move this Lesson has been part of because a holiday (or
  // similar calendar exception) displaced its own originally-scheduled
  // date. `[]` for the overwhelming majority of Lessons that have never
  // been touched by this feature; absent entirely on any Lesson
  // document persisted before this field existed (every reader below
  // defaults it via `|| []`, so no migration is needed). See
  // createRescheduleRecord()/rescheduleConceptsForHoliday() below.
  rescheduleHistory = [],
} = {}) {
  return {
    id: id || generateId(),
    planningCycleId,
    classroomId,
    date,
    teachingSlotId,
    curriculumUnitId,
    conceptIds,
    executedConceptIds,
    // `carriedForwardConceptIds` — subset of conceptIds: planned here,
    // but moved to a different (future) occurrence instead of being
    // taught here. Stays listed in conceptIds (so this Lesson's own
    // Planned Concepts list keeps showing it, per the approved
    // reference) — never removed, never re-added elsewhere as a new
    // id. See services/carryForwardService.js for the one place this
    // is ever set.
    carriedForwardConceptIds,
    // `conceptProvenance` — { [conceptId]: { fromLessonId,
    // fromTeachingSlotId, carriedAt } }, present ONLY for concepts that
    // arrived on THIS Lesson via carry-forward from a different one.
    // Together with the source Lesson's own carriedForwardConceptIds
    // entry, this is what makes "D was originally planned for Tuesday,
    // carried forward, then taught on Thursday" fully reconstructable
    // later without inspecting anything beyond these two Lessons — see
    // services/carryForwardService.js.
    conceptProvenance,
    objectives,
    bigQuestion,
    planSummary,
    assessmentNote,
    lessonPlanId,
    sequenceIndex,
    estimatedMinutes,
    actualMinutes,
    status,
    // `teacherReflection` — free text, nullable. The Period Detail
    // panel's own "Teacher Reflection" field (see the approved
    // reference) — a private note against this one occurrence, not
    // shown to students.
    teacherReflection,
    // `feedbackSharedAt` — ISO string, nullable. Set once, the moment
    // "Share feedback with students" is tapped (see
    // services/timetableLessonService.js's shareFeedbackWithStudents())
    // — not the same moment as executedConceptIds being populated: a
    // teacher may mark concepts executed and still want to add a
    // reflection or double check before actually sharing. The concept
    // list students actually see is always resolved fresh from
    // executedConceptIds at read time (see getFeedbackEligibleConceptIds()
    // below) — this field only gates *whether* that's happened yet,
    // never a separate copy of *which* concepts.
    feedbackSharedAt,
    rescheduleHistory,
  };
}

/**
 * Pure validation: which of `executedConceptIds` are NOT actually in
 * this Lesson's own `conceptIds` — an empty array means the whole set
 * is valid. Kept here, in this dependency-free model file, rather than
 * inline in services/timetableLessonService.js (which transitively
 * imports the real Firestore SDK from a remote https:// URL that
 * Node's own test runner cannot resolve at all) specifically so this
 * one invariant — "executedConceptIds must be a subset of conceptIds"
 * — stays directly unit-testable.
 */
export function findInvalidExecutedConceptIds(lesson, executedConceptIds) {
  return executedConceptIds.filter((conceptId) => !lesson.conceptIds.includes(conceptId));
}

/** Only executed concepts are eligible for student feedback — see this file's own executedConceptIds doc comment for why this is scoped per-occurrence, not the classroom-wide LearningConcept.status. */
export function getFeedbackEligibleConceptIds(lesson) {
  return [...lesson.executedConceptIds];
}

/**
 * Reassigns `lesson` to a different curriculumUnitId — a pure,
 * dependency-free mutation (same rationale as findInvalidExecutedConceptIds()
 * above: directly unit-testable without pulling in
 * services/plannerRepository.js's real Firestore import). Kept here,
 * not inline in ui/views/TimetableView.js's own openEditLessonUnitFlow(),
 * so this one invariant — "a concept id from the old unit is meaningless
 * against the new one, so every concept-related field resets rather
 * than silently carrying stale ids across" — stays covered by a real
 * test rather than only ever exercised by hand in a browser.
 *
 * Every concept-related field resets, not just conceptIds: executedConceptIds/
 * carriedForwardConceptIds/conceptProvenance would otherwise keep
 * referencing concept ids that no longer belong to this lesson's own
 * unit, and feedbackSharedAt would otherwise still claim feedback was
 * shared for a set of concepts that no longer applies.
 *
 * Caller's responsibility (not this function's): deciding whether to
 * warn/confirm before calling this when the lesson already has
 * concepts, and persisting the result afterward — this only ever
 * mutates the in-memory `lesson` object handed to it.
 */
export function resetLessonForUnitChange(lesson, newUnitId) {
  lesson.curriculumUnitId = newUnitId;
  lesson.conceptIds = [];
  lesson.executedConceptIds = [];
  lesson.carriedForwardConceptIds = [];
  lesson.conceptProvenance = {};
  lesson.feedbackSharedAt = null;
  return lesson;
}

/**
 * Moves one planned concept from `sourceLesson` to `targetLesson` —
 * a pure, dependency-free mutation (no Firestore, no id generation)
 * kept in this model file for the same reason findInvalidExecutedConceptIds()
 * above is: so this exact invariant stays directly unit-testable
 * without pulling in services/plannerRepository.js's real Firestore
 * import. The orchestration around it (finding/creating the target
 * Lesson, persisting both afterward) lives in
 * services/carryForwardService.js.
 *
 * Never clones the LearningConcept and never generates a new id —
 * `conceptId` is reused verbatim on both ends. It STAYS in
 * sourceLesson.conceptIds (so that lesson's own Planned Concepts list
 * keeps listing it, matching the approved reference) but is recorded
 * in sourceLesson.carriedForwardConceptIds so it's never mistaken for
 * "still awaiting execution here." It's appended to
 * targetLesson.conceptIds, with a conceptProvenance entry recording
 * exactly where it came from and when — together, these two Lessons
 * fully reconstruct "originally planned on Tuesday, carried forward,
 * (eventually) taught on Thursday" with nothing else to inspect.
 *
 * Throws rather than silently doing something ambiguous when the
 * concept isn't actually eligible to be carried: not planned on the
 * source at all, already executed there (nothing left to carry), already
 * carried forward once before (carrying the same concept twice would
 * leave two different target lessons both claiming it), or already
 * present on the target (would silently duplicate it in conceptIds).
 */
export function carryForwardConcept({ sourceLesson, targetLesson, conceptId, sourceTeachingSlotId, carriedAt }) {
  if (!sourceLesson.conceptIds.includes(conceptId)) {
    throw new Error(`Concept ${conceptId} is not planned on the source lesson`);
  }
  if (sourceLesson.executedConceptIds.includes(conceptId)) {
    throw new Error(`Concept ${conceptId} was already executed — nothing to carry forward`);
  }
  if (sourceLesson.carriedForwardConceptIds.includes(conceptId)) {
    throw new Error(`Concept ${conceptId} has already been carried forward`);
  }
  if (targetLesson.conceptIds.includes(conceptId)) {
    throw new Error(`Concept ${conceptId} is already planned on the target lesson`);
  }

  sourceLesson.carriedForwardConceptIds = [...sourceLesson.carriedForwardConceptIds, conceptId];
  targetLesson.conceptIds = [...targetLesson.conceptIds, conceptId];
  targetLesson.conceptProvenance = {
    ...targetLesson.conceptProvenance,
    [conceptId]: { fromLessonId: sourceLesson.id, fromTeachingSlotId: sourceTeachingSlotId, carriedAt },
  };

  return { sourceLesson, targetLesson };
}

/**
 * Moves one planned concept from `sourceLesson` to `targetLesson` as a
 * pure PLANNING rearrangement — deliberately NOT carryForwardConcept()
 * above, and never to be confused with it (2026-10 Concepts panel
 * redesign, per explicit product direction: "Move to..." is a planning
 * action, Carry Forward is a teaching/progress action, and moving a
 * concept during planning must never CREATE a NEW teaching-history/
 * carry-forward state). The concept is fully removed from
 * sourceLesson.conceptIds (not kept there and tagged, the way
 * carryForwardConcept() deliberately does) — after this call, the
 * concept reads exactly as if it had always been planned on
 * targetLesson and never planned on sourceLesson at all, with no trace
 * left behind of the rearrangement ever happening.
 *
 * `conceptProvenance` — IF `sourceLesson` already had a real provenance
 * entry for this concept (i.e. the source itself was the TARGET of an
 * earlier carryForwardConcept() call, and the concept hasn't been
 * taught since), that entry is carried forward to `targetLesson`
 * VERBATIM, never fabricated, regenerated, or dropped — see this
 * function's own 2026-10 fix: previously this entry was silently
 * discarded on every move, which meant moving an already-carried-
 * forward concept a second time (whether via an ordinary "Move to..."
 * planning action — services/timetableLessonService.js's own
 * moveConceptToTeachingSlot() — or a Holiday automatically displacing
 * the Lesson that received it — services/holidayRescheduleService.js's
 * own rescheduleConceptsForHoliday()) made "where did this concept
 * ORIGINALLY come from" permanently unrecoverable, breaking this
 * field's own documented "fully reconstructable... nothing else to
 * inspect" guarantee. A concept with no existing provenance (the
 * overwhelming common case — an ordinarily-planned concept moved for
 * the first time) still gets none on the target, exactly as before.
 *
 * Same eligibility guards as carryForwardConcept() (not planned on the
 * source / already executed / already carried forward / already on the
 * target), for analogous reasons: a concept that's already been taught
 * or is already mid-carry-forward is teaching history, not something
 * still open to ordinary planning rearrangement.
 */
export function moveConcept({ sourceLesson, targetLesson, conceptId }) {
  if (!sourceLesson.conceptIds.includes(conceptId)) {
    throw new Error(`Concept ${conceptId} is not planned on the source lesson`);
  }
  if (sourceLesson.executedConceptIds.includes(conceptId)) {
    throw new Error(`Concept ${conceptId} was already executed — nothing to move`);
  }
  if (sourceLesson.carriedForwardConceptIds.includes(conceptId)) {
    throw new Error(`Concept ${conceptId} has already been carried forward`);
  }
  if (targetLesson.conceptIds.includes(conceptId)) {
    throw new Error(`Concept ${conceptId} is already planned on the target lesson`);
  }

  sourceLesson.conceptIds = sourceLesson.conceptIds.filter((existingId) => existingId !== conceptId);

  const existingProvenance = sourceLesson.conceptProvenance[conceptId];
  if (existingProvenance) {
    const { [conceptId]: _removed, ...rest } = sourceLesson.conceptProvenance;
    sourceLesson.conceptProvenance = rest;
    // Carried forward UNCHANGED — fromLessonId/fromTeachingSlotId/
    // carriedAt still point at the concept's own original carry-
    // forward source, never this intermediate hop, so a chain of
    // several moves still answers "where did this ORIGINALLY come
    // from" with the true origin, not the most recent stop.
    targetLesson.conceptProvenance = { ...targetLesson.conceptProvenance, [conceptId]: existingProvenance };
  }

  targetLesson.conceptIds = [...targetLesson.conceptIds, conceptId];

  return { sourceLesson, targetLesson };
}

/**
 * One entry in a Lesson's own `rescheduleHistory[]` — holiday
 * rescheduling milestone. `direction` distinguishes the two sides of
 * the SAME move (`'sent'` on the source Lesson, `'received'` on the
 * destination Lesson), both sharing the same `moveId` so either side
 * can be correlated back to its counterpart without a separate lookup
 * table. Deliberately NOT reusing conceptProvenance's shape — that
 * field exists specifically for carryForwardConcept()'s own teaching/
 * progress semantics (see this file's own header comment on that
 * function) and is read by ui/views/TimetableView.js's own "N carried
 * in" badge; a holiday-displaced concept is a planning rearrangement
 * (same category as moveConcept() itself), not a teaching-progress
 * event, so it gets its own distinct, non-conflated record instead.
 */
export function createRescheduleRecord({ id, moveId, direction, conceptIds, fromTeachingSlotId, fromDate, toTeachingSlotId, toDate, toLessonId, fromLessonId, exceptionId, reason, movedAt }) {
  return {
    id: id || generateId(),
    moveId,
    direction, // 'sent' | 'received'
    conceptIds: [...conceptIds],
    fromTeachingSlotId,
    fromDate,
    toTeachingSlotId,
    toDate,
    toLessonId,
    fromLessonId,
    exceptionId, // models/CalendarException.js's own id — the holiday that caused this move
    reason, // short, stable machine reason string — 'holiday' today, room for another cause later without a shape change
    movedAt, // ISO string — caller-supplied (see carryForwardConcept()'s own `carriedAt` parameter for the identical, established convention of never calling getCurrentIsoDate() from inside this dependency-free model file)
  };
}

/**
 * Moves every one of `conceptIds` from `sourceLesson` to `targetLesson`
 * in one coherent holiday-reschedule move, reusing moveConcept() itself
 * for each one (never a hand-rolled bulk mutation that could drift from
 * that function's own eligibility guards/invariants) and recording one
 * paired rescheduleHistory entry on each Lesson. All-or-nothing: if ANY
 * concept in `conceptIds` is ineligible (already executed, already
 * carried forward, or already present on the target), moveConcept()
 * itself throws before any mutation for that concept happens — but
 * since this function calls moveConcept() in a loop, a later failure
 * could leave earlier concepts already moved. Callers (see
 * services/holidayRescheduleService.js) are expected to have already
 * filtered `conceptIds` down to exactly the eligible set (lesson's own
 * conceptIds minus executedConceptIds minus carriedForwardConceptIds)
 * before calling this, so this guard is defense-in-depth, not the
 * primary filter.
 *
 * Sets `sourceLesson.status = 'rescheduled'` when, after this move,
 * NOTHING planned on it remains un-executed and un-moved (every
 * concept is now either executed, carried forward, or just
 * rescheduled) — using this model's own pre-existing `status` field
 * (see createLesson()'s own doc comment: 'rescheduled' was already
 * listed as a valid value, "ready for a future UI to call," and
 * nothing else in the codebase reads/writes Lesson.status outside
 * services/plannerService.js's own PlanningCycle-scoped
 * updateLessonStatus(), which this function deliberately does not
 * call — a holiday-displaced Lesson may not even belong to a
 * PlanningCycle at all). Left as 'planned' when the source lesson still
 * has other, untouched concepts of its own (a partially-executed
 * lesson keeps its normal status — only ITS OWN remaining content, not
 * this one Lesson record, determines whether more work is left).
 */
export function rescheduleConceptsForHoliday({ sourceLesson, targetLesson, conceptIds, fromTeachingSlotId, fromDate, toTeachingSlotId, toDate, exceptionId, movedAt, reason = 'holiday' }) {
  if (conceptIds.length === 0) return { sourceLesson, targetLesson };

  conceptIds.forEach((conceptId) => {
    moveConcept({ sourceLesson, targetLesson, conceptId });
  });

  const moveId = generateId();
  sourceLesson.rescheduleHistory = [
    ...(sourceLesson.rescheduleHistory || []),
    createRescheduleRecord({
      moveId,
      direction: 'sent',
      conceptIds,
      fromTeachingSlotId,
      fromDate,
      toTeachingSlotId,
      toDate,
      toLessonId: targetLesson.id,
      fromLessonId: sourceLesson.id,
      exceptionId,
      reason,
      movedAt,
    }),
  ];
  targetLesson.rescheduleHistory = [
    ...(targetLesson.rescheduleHistory || []),
    createRescheduleRecord({
      moveId,
      direction: 'received',
      conceptIds,
      fromTeachingSlotId,
      fromDate,
      toTeachingSlotId,
      toDate,
      toLessonId: targetLesson.id,
      fromLessonId: sourceLesson.id,
      exceptionId,
      reason,
      movedAt,
    }),
  ];

  // 'rescheduled' is reserved for "this whole occurrence relocated —
  // nothing was ever taught here:" nothing executed AND nothing open
  // left behind (every concept either just moved away, or had already
  // been carried forward separately beforehand). A lesson where SOME
  // concept really was taught on the original date keeps its ordinary
  // 'planned' status — real teaching history happened here, so
  // "rescheduled" (implying the whole thing simply moved) would
  // misdescribe it, even though part of its own content did move.
  const sourceHasRemainingOpenWork = sourceLesson.conceptIds.some(
    (conceptId) => !sourceLesson.executedConceptIds.includes(conceptId) && !sourceLesson.carriedForwardConceptIds.includes(conceptId)
  );
  if (!sourceHasRemainingOpenWork && sourceLesson.executedConceptIds.length === 0) sourceLesson.status = 'rescheduled';

  return { sourceLesson, targetLesson };
}

/**
 * Removes one concept from a Lesson's own plan entirely — "Remove from
 * lesson," never "delete the concept" (see
 * services/learningRecordTeacherService.js's own deleteConcept() for
 * that separate, unit-wide, canonical-Knowledge-Model action this
 * function never calls or duplicates — this only ever edits which
 * concepts THIS Lesson references, never the LearningConcept itself).
 * Clears every concept-keyed field, not just conceptIds — the same
 * "every field resets together" discipline resetLessonForUnitChange()
 * above follows — so executedConceptIds/carriedForwardConceptIds/
 * conceptProvenance never end up referencing a concept id this Lesson
 * no longer plans at all.
 */
export function removeConceptFromLesson(lesson, conceptId) {
  lesson.conceptIds = lesson.conceptIds.filter((existingId) => existingId !== conceptId);
  lesson.executedConceptIds = lesson.executedConceptIds.filter((existingId) => existingId !== conceptId);
  lesson.carriedForwardConceptIds = lesson.carriedForwardConceptIds.filter((existingId) => existingId !== conceptId);
  if (lesson.conceptProvenance[conceptId]) {
    const { [conceptId]: _removed, ...rest } = lesson.conceptProvenance;
    lesson.conceptProvenance = rest;
  }
  return lesson;
}
